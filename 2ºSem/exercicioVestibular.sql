USE VESTIBULAR

CREATE TABLE PAGAMENTO (
    CodPag INT CONSTRAINT PK_PAGAMENTO PRIMARY KEY IDENTITY(1,1),
    ValorPago MONEY,
    ValorJurosMulta MONEY,
    dtVencto DATE CONSTRAINT DF_DATAVENCIMENTO DEFAULT(DATEADD(DAY, 10, GETDATE())),
    dtPagto DATE,
    dtRegistro DATE
)

CREATE TABLE CANDIDATO (
    CodCan INT CONSTRAINT PK_CANDIDATO PRIMARY KEY IDENTITY(1,1),
    Nome VARCHAR(80),
    Endereco VARCHAR(200),
    CPF CHAR(11),
    RG CHAR(10),
    Situacao VARCHAR(30) CONSTRAINT CK_SITUACAO_CANDIDATO CHECK(Situacao IN ('Aprovado', 'Reprovado', 'Aprovado em 2ª chamada'))
)

CREATE TABLE CURSO (
    CodCur INT CONSTRAINT PK_CURSO PRIMARY KEY IDENTITY(1,1),
    Nome VARCHAR(80),
    CargaHoraria INT CONSTRAINT CK_CARGA_HORARIA CHECK (CargaHoraria IN (2800, 3600)),
    NroVagas INT
)

CREATE TABLE INSCRICAO (
    CodIns INT CONSTRAINT PK_INSCRICAO PRIMARY KEY IDENTITY(1,1),
    Nota FLOAT,
    AnoInscr INT CONSTRAINT DF_ANOINSCR DEFAULT(YEAR(GETDATE())),
    DataInscricao DATE CONSTRAINT DF_DATAINSCRICAO DEFAULT(GETDATE()),
    Situacao VARCHAR(50) CONSTRAINT CK_SITUACAO_INSCRICAO CHECK(Situacao IN ('Aguardando pagamento', 'Cancelado', 'Encerrado', 'Pago')),
    CodCan INT CONSTRAINT FK_CANDIDATO FOREIGN KEY REFERENCES CANDIDATO(CodCan),
    Opcao1 INT CONSTRAINT FK_OP1_CURSO FOREIGN KEY REFERENCES CURSO(CodCur),
    Opcao2 INT CONSTRAINT FK_OP2_CURSO FOREIGN KEY REFERENCES CURSO(CodCur),
    CodPag INT CONSTRAINT FK_PAGAMENTO FOREIGN KEY REFERENCES PAGAMENTO(CodPag),
    CONSTRAINT CK_OPCOES_CURSO CHECK(Opcao1 != Opcao2),
    CONSTRAINT UQ_CANDIDATO_ANO UNIQUE(AnoInscr, CodCan)
)

